function add(pool, id, nodes) {
  const out = {};
  for (const k in nodes) {
    if (!Array.isArray(nodes[k])) continue;   // rare: доля, с которой сцена выпадает (редкие сцены)
    const [text, ...cs] = nodes[k];
    out[k] = { text, choices: cs.map(c => typeof c === "string" ? { text: c, next: null } : { text: c[0], next: c[1] === undefined ? null : c[1], ...(c[2] || {}) }) };
  }
  SCENES[id] = { start: "s", nodes: out, rare: nodes.rare }; pool.push(id);
}
