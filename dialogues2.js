//   delay - задержка в минутах (проверка документов и т.п.)
//   cost  - потратить свои деньги (без штрафа), why - на что
//   moodD - настроение водителя (+/-, в процентах)
//   perk  - подарок навсегда: "kit", "cam", "thermos", "water", "charge", "covers" (как покупка в магазине)
//   end   - пассажир выходит прямо сейчас (по карте - оплата за проеханное, наличными - ничего)
//   roll  - [шанс, узел если повезло, узел если нет] - исход решает случай
//   giftR - [от, до] - случайная благодарность в этих пределах
//   rateHit - сразу добавить в рейтинг водителя оценку (жалоба), например 1
//   prio  - изменить приоритет (жалоба в сервис); с видеорегистратором жалоба не проходит
